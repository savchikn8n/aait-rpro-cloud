# -*- coding: utf-8 -*-
"""
Каталог моделей R-Pro: поиск и загрузка в сцену.

Каталог — это три тысячи моделей: роботы, конвейеры, станки, захваты,
шаблоны планировок. Python-API программы его не показывает, поэтому берём
описание каталога там же, откуда его берёт сама R-Pro, — файлом с сайта
поставщика. Адрес виден в её журнале при запуске.

Была попытка вытащить то же самое из локальной базы каталога (файл .sdf).
Разбор двоичного файла дал адреса моделей, но названия распознавались лишь у
16 процентов: в базе перемешаны две кодировки, а поля идут вперемешку с
двоичным мусором, который после расшифровки выглядит как связный текст.
Готовый XML даёт ровно те же модели с чистыми названиями, поэтому тот подход
выброшен.

Найденную модель загружает мост: app.load(адрес) ставит её в сцену.
"""

from __future__ import annotations

import os
import re
import time
import xml.etree.ElementTree as ET

import requests

import glossary
import kb

ИСТОЧНИК = os.environ.get(
    "RPRO_CATALOG_URL", "https://download.r-pro.digital/v204/catalog.xml")

# Каталог меняется редко, а весит почти пять мегабайт: держим его на диске.
КЕШ = os.path.join(os.environ.get("LOCALAPPDATA", os.environ.get("TEMP", ".")),
                   "R-Pro", "AIAgentBridge", "catalog.xml")
СРОК_КЕША = 7 * 24 * 3600.0

_модели: list[dict] = []


class ОшибкаКаталога(RuntimeError):
    """Каталог недоступен."""


def _скачать() -> bytes:
    try:
        ответ = requests.get(ИСТОЧНИК, timeout=120)
    except requests.exceptions.RequestException as сбой:
        raise ОшибкаКаталога(
            f"каталог не скачался с {ИСТОЧНИК}: {сбой}") from сбой
    if ответ.status_code != 200:
        raise ОшибкаКаталога(f"каталог ответил {ответ.status_code}")
    return ответ.content


def _сырой_каталог(обновить: bool = False) -> bytes:
    свежий = (not обновить and os.path.isfile(КЕШ)
              and time.time() - os.path.getmtime(КЕШ) < СРОК_КЕША)
    if свежий:
        with open(КЕШ, "rb") as файл:
            return файл.read()

    try:
        данные = _скачать()
    except ОшибкаКаталога:
        # Сеть могла пропасть, а старый каталог лучше никакого.
        if os.path.isfile(КЕШ):
            with open(КЕШ, "rb") as файл:
                return файл.read()
        raise

    os.makedirs(os.path.dirname(КЕШ), exist_ok=True)
    with open(КЕШ, "wb") as файл:
        файл.write(данные)
    return данные


def загрузить(обновить: bool = False) -> list[dict]:
    """Читает каталог и возвращает список моделей."""
    global _модели
    if _модели and not обновить:
        return _модели

    корень = ET.fromstring(_сырой_каталог(обновить))

    модели = []
    for узел in корень:
        адрес = (узел.findtext("File") or "").strip()
        имя = (узел.findtext("Name") or "").strip()
        if not адрес or not имя:
            continue
        модели.append({
            "имя": имя,
            "описание": (узел.findtext("Description") or "").strip()[:300],
            "раздел": (узел.findtext("Type") or "").strip(),
            "производитель": (узел.findtext("Manufacturer") or "").strip(),
            "адрес": адрес,
            # Расширение .rpro у всех моделей, отличает их папка на сервере:
            # шаблоны и готовые планировки лежат в /Layouts/.
            "тип": "планировка" if "/layouts/" in адрес.lower() else "компонент",
        })

    _модели = модели
    return _модели


def найти(запрос: str, предел: int = 15) -> list[dict]:
    """
    Ищет модели по словам запроса.

    Совпадение ищется по названию, разделу, производителю и описанию: так
    «робот kuka» находит роботов KUKA, а «замкнутый конвейер» — шаблон
    планировки. Слова сравниваются по основе («конвейеры» = «конвейер»), а
    бытовые слова переводятся в термины каталога через glossary: «хваталка»
    ищет ещё и раздел «Роботы (инструменты)».

    Раньше модель проходила, только если совпали все слова запроса, и
    «робот-паллетайзер на 100 кг» не находил ничего. Теперь модели
    упорядочены по очкам: совпадение в названии дороже, чем в разделе, а в
    разделе — дороже, чем в описании. Первыми идут модели, где совпало
    больше слов самого запроса: «робот fanuc 10 кг» ставит FANUC выше ABB,
    даже если «кг» не нашлось нигде.
    """
    слова = _основы(запрос)
    if not слова:
        return []
    термины = [о for т in glossary.expand(запрос) for о in _основы(т) if о not in слова]

    найдено = []
    for модель in загрузить():
        if "_основы" not in модель:
            модель["_основы"] = (_основы(модель["имя"] + " " + модель["производитель"]),
                                 _основы(модель["раздел"]), _основы(модель["описание"]))
        имя, раздел, описание = модель["_основы"]

        def вес(основа: str) -> float:
            if основа in имя:
                return 3.0
            if основа in раздел:
                # «робот» — это скорее раздел «Роботы», чем «Оборудование - Робот».
                return 2.5 if len(раздел) == 1 else 2.0
            if основа in описание:
                return 1.0
            return 0.0

        свои = [вес(с) for с in слова]
        по_словарю = [вес(т) for т in термины]
        if not any(свои) and not any(в >= 2 for в in по_словарю):
            continue
        очки = sum(свои) + 0.5 * sum(по_словарю)
        # Термин словаря в названии или разделе считается как слово запроса,
        # а при равенстве решают очки: на «рельс» робот ждёт «линейную
        # направляющую робота», а не «рельсовую опору» крана, где «рельс»
        # совпал буквально.
        совпало = sum(1 for в in свои if в) + (1 if any(в >= 2 for в in по_словарю) else 0)
        # Совпадения в названии и разделе важнее совпадений в описании: на
        # «замкнутого конвейера по центру» (журнал 08.10) «Модуль отслеживания
        # продукта» набрал «по» и «центр» в описании и обошёл «Замкнутый
        # конвейер», у которого оба слова — в названии.
        сильных = sum(1 for в in свои if в >= 2) + (1 if any(в >= 2 for в in по_словарю) else 0)
        # «Добавь конвейер» — это «Конвейер», а не «Спиральный конвейер»: имя,
        # целиком состоящее из слов запроса, идёт первым, при прочих равных —
        # более короткое (без лишних уточнений).
        точно = 1 if имя and имя <= set(слова) | {"r", "pro"} else 0
        лишних = len(имя - set(слова))
        найдено.append((сильных, совпало, точно, очки, -лишних, модель))

    найдено.sort(key=lambda x: x[:5], reverse=True)
    return [x[5] for x in найдено[:предел]]


_СЛОВО = re.compile(r"[a-zA-Zа-яА-ЯёЁ0-9]+")


def _основы(текст: str) -> set[str]:
    """Основы слов для сравнения: «конвейеры», «конвейера» → «конвей»."""
    return {kb.tokens_stem(с) for с in _СЛОВО.findall(текст or "")
            if len(с) > 1 and kb.tokens_stem(с) not in kb.STOP}
