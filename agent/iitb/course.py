def catalog_text() -> str:
    out = ["**Курс ИИТБ Skill Camp — что агент умеет делать по просьбе** (просто попросите, например «собери роутер»; «как …» — объясню):", ""]
    for n, (title, what, state) in LESSONS.items():
        mark = {"готово": "✔", "частично": "◐", "в работе": "…", "только интерфейс": "✋"}.get(state, "•")
        out.append(f"{mark} **{n}. {title}** — {what}")
    out.append("")
    out.append("Файлы результатов — `examples/iitb/Урок_N.rpro` (рядом видео/PDF/CSV и снимки в `shots/`). "
               "Задание заменяет текущую сцену.")
    return "\n".join(out)


def _number(low: str) -> int | None:
    m = _NUM.search(low)
    if m:
        n = int(m.group(1) or m.group(2))
        return n if n in LESSONS else None
    if _COURSE.search(low):
        for w, n in _WORDS.items():
            if w in low:
                return n
    return _topic(low, only_build=True)


# Уроки, где задание строит свою учебную сцену (запуск по просьбе заменит сцену — агент сперва спросит).
# Остальные темы (видео, дашборд, ячейка, детектор) применяются к сцене пользователя: их по просьбе не запускаем,
# а подкладываем модели проверенный рецепт (recipe) — она делает это в его сцене через rpro_exec.
BUILD_LESSONS = (10, 11, 12, 14, 15, 16)


def _topic(low: str, only_build: bool = False) -> int | None:
    """Номер урока по теме просьбы или None. Депаллетизация проверяется раньше паллетирования."""
    for n in (16, 14, 11, 12, 13, 15, 10, 8, 6, 5):
        if only_build and n not in BUILD_LESSONS:
            continue
        if _TOPIC[n].search(low):
            return n
    return None


def recipe(low: str) -> tuple[int, str] | None:
    """(номер урока, рецепт «Как это делает агент») по теме просьбы — проверенный код для rpro_exec."""
    n = _topic(low)
    if n is None and re.search(r"construct|get\s*assembly", low):
        n = 11    # слова из видео про сборку: ответ обязан предупредить о зацикливании (урок 11)
    if n is None:
        return None
    p = HERE / "lessons" / f"L{n:02d}.md"
    if not p.exists():
        return None
    m = re.search(r"^## Как это делает агент[^\n]*\n(.*?)(?=^## |\Z)", p.read_text(encoding="utf-8"), re.M | re.S)
    return (n, m.group(1).strip()) if m else None


def intent(text: str) -> tuple[str, int] | None:
    """('run', N) — выполнить задание; ('explain', N) — объяснить урок; None — не про курс.

    Выполняем только по прямой просьбе («выполни…», «сделай…», «урок N»): вопрос «как делать
    урок 5?» объясняем, сцену не трогаем."""
    t = (text or "").strip()
    low = t.lower().replace("ё", "е")
    n = _number(low)
    if n is None:
        return None
    if low.startswith("/"):
        return ("run", n)
    named = bool(_NUM.search(low) or _COURSE.search(low))   # урок назван прямо или сказано «из курса ИИТБ»
    if _HOW.search(low):
        # «Как настроить ожидание сигнала?» без слов о курсе — вопрос по теме: отвечает общий поиск
        # (проверенные факты и конспекты уроков вместе), а не только конспект одного урока
        return ("explain", n) if named else None
    if _DO.search(low):
        return ("run", n)
    return ("explain", n) if _NUM.search(low) else None


def parse(text: str) -> int | None:
    r = intent(text)
    return r[1] if r else None


def explain_text(n: int) -> str:
    """Суть урока и практическое задание — из конспекта lessons/L0N.md."""
    p = HERE / "lessons" / f"L{n:02d}.md"
    if not p.exists() or n not in LESSONS:
        return f"В курсе нет урока {n}."
    body = p.read_text(encoding="utf-8")
    parts = re.split(r"^## +", body, flags=re.M)
    pick = [x for x in parts[1:] if x.startswith(("Суть урока", "Практическое задание", "Лайфхаки"))]
    title = LESSONS[n][0]
    blocks = []
    for x in pick:
        head, _, rest = x.partition(chr(10))
        blocks.append("**" + head + "**" + chr(10) + rest.strip())
    text = (chr(10) * 2).join(blocks)
    state = LESSONS[n][2]
    tail = ("Агент выполняет это задание сам — просто попросите его об этом." if state in ("готово", "частично")
            else "Это задание агент пока сам не выполняет.")
    nl = chr(10) * 2
    return f"**Урок {n}. {title}**{nl}{text}{nl}{tail}"


def run_text(n: int) -> str:
    """Выполняет задание урока n в живой R-Pro и пересказывает итог."""
    if n not in LESSONS:
        return f"В курсе нет урока {n}. Уроки: 1–16 ."
    title, what, state = LESSONS[n]
    if state == "только интерфейс":
        return (f"**Урок {n}. {title}** — в Python-API R-Pro для этого нет инструментов ({what}). "
                f"Выполняется кнопками области «Чертёж»; подсказка: `/справка курс чертёж`.")
    if state == "в работе":
        return f"Задание урока {n} («{title}») ещё не готово у агента. Объяснение: `/справка курс {title}`."
    sys.path.insert(0, str(HERE))
    sys.path.insert(0, str(HERE.parent))
    import runner  # noqa: E402
    info = runner.run(n, save=False)   # сцена остаётся в R-Pro; файлы-образцы examples/iitb не перезаписываем
    lines = [f"**Урок {n}. {title}** — выполнено за {info.get('секунд')} с.", f"Что сделано: {what}.", "Сцена осталась в R-Pro — можно смотреть и править."]
    if info.get("файл"):
        lines.append(f"Файл: `{info['файл']}`.")
    res = info.get("результат") or {}
    for key in ("видео", "pdf", "csv"):
        v = res.get(key)
        if isinstance(v, dict) and v.get("файл"):
            lines.append(f"{key}: `{v['файл']}`")
        elif isinstance(v, str) and v:
            lines.append(f"{key}: `{v}`")
    msgs = res.get("сообщения") or res.get("ошибки")
    if msgs:
        lines.append("В выводе R-Pro есть сообщения: " + "; ".join(str(m)[:80] for m in msgs[:3]))
    return "\n".join(lines)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    arg = " ".join(sys.argv[1:])
    print(catalog_text() if not arg else run_text(int(arg)))
