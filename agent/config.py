import json
import os


def _load_settings_files() -> None:
    local = os.environ.get("LOCALAPPDATA", "")
    paths = [
        os.path.join(local, "R-Pro", "AIAgentBridge", "settings.json"),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "defaults.json"),
    ]
    for path in paths:
        try:
            with open(path, encoding="utf-8-sig") as handle:
                values = json.load(handle)
        except (OSError, ValueError):
            continue
        if isinstance(values, dict):
            for name, value in values.items():
                os.environ.setdefault(str(name), str(value))


_load_settings_files()


def _trust_windows_certificates() -> None:
    """Проверять HTTPS по хранилищу сертификатов Windows.

    Сервер моделей стоит за https://….itc.kl.avtotor.ru, а сертификат там
    выпущен внутренним центром сертификации предприятия. Python по умолчанию
    доверяет только своему набору публичных центров и такой сертификат
    отвергает. На машинах в домене внутренний центр уже есть в хранилище
    Windows — truststore учит Python смотреть туда.
    """
    try:
        import truststore
    except ImportError:
        return
    truststore.inject_into_ssl()


_trust_windows_certificates()

