# -*- coding: utf-8 -*-
"""
Как уроки Academy меняют поиск агента: python retrieval_probe.py

Без модели: типичные вопросы новичка → топ-2 фрагмента, как их подкладывает
chat._kb_prefetch. Показывает, откуда взят каждый фрагмент и вытеснили ли
уроки справку. Просто смотрим глазами и считаем долю.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.stdout.reconfigure(encoding="utf-8")

import kb  # noqa: E402

QUESTIONS = [
    "как сделать конвейер который останавливается по датчику",
    "как создать свойство-кнопку у компонента",
    "как записать видео симуляции",
    "как подключить сигналы робота к конвейеру",
    "как сделать так чтобы детали появлялись на конвейере",
    "как научить робота брать деталь и класть на паллету",
    "как сделать паллетизацию",
    "как посчитать время цикла",
    "как проверить достижимость робота",
    "как импортировать CAD модель и упростить её",
    "как сделать захват для робота",
    "как настроить столкновения у робота",
    "как подключить ПЛК по OPC UA",
    "как сделать позиционер для детали",
    "как написать скрипт который ждёт сигнал",
    "как сделать свою команду в меню",
    "как сохранить вывод в Output панель",
    "как сделать сборку из нескольких деталей",
    "как задать маршрут продуктов по материалу",
    "как отобразить статистику загрузки оборудования",
    "что такое контейнер в компоненте",
    "как измерить расстояние между компонентами",
    "как замкнуть программу робота в цикл",
    "как пользоваться привязкой snap",
    "как скрыть компонент в сцене",
]


def main() -> None:
    from_academy = total = 0
    for q in QUESTIONS:
        hits = [h for h in kb.search(q, 4) if h["score"] >= 1.0][:2]
        tags = []
        for h in hits:
            total += 1
            from_academy += h["source"] == "academy"
            tags.append(f"{h['source']}:{h['title'].split(' / ')[-1][:34]}"
                        + (f" ({h['part']})" if h["part"] else "") + f" {h['score']}")
        print(f"- {q}\n    " + "\n    ".join(tags or ["(пусто)"]))
    print(f"\nфрагментов из уроков в топ-2: {from_academy} из {total}")


if __name__ == "__main__":
    main()
