_WORD = re.compile(r"[a-zA-Zа-яА-ЯёЁ0-9_/\-]+")


def expand(query: str) -> list[str]:
    """Термины программы, которые подразумевает запрос. Без повторов."""
    q = (query or "").lower().replace("ё", "е")
    words = _WORD.findall(q)
    found: list[str] = []
    def matches(p: str) -> bool:
        p = p.replace("ё", "е")
        if " " in p:
            return p in q
        if p.endswith("$"):
            return p[:-1] in words
        return any(w.startswith(p) for w in words)

    for prefixes, terms in TERMS:
        hit = any(matches(p) for p in prefixes)
        if hit:
            for t in terms:
                if t not in found:
                    found.append(t)
    return found


def expanded_query(query: str) -> str:
    extra = expand(query)
    return query + (" " + " ".join(extra) if extra else "")


